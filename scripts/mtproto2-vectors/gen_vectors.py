"""Generator of known-answer vectors for the KoSta MTProto 2.0 crypto layer.

This script is an *independent* (Python) implementation of AES-256-IGE and the
MTProto 2.0 key derivation. It is used to cross-check the Rust implementation in
`kosta-crypto` and to regenerate the KAT constants embedded in its tests.

Usage:
    python scripts/mtproto2-vectors/gen_vectors.py

Requires: pycryptodome (`pip install pycryptodome`).
"""

from Crypto.Cipher import AES

import hashlib


def ige_encrypt(key: bytes, iv: bytes, data: bytes) -> bytes:
    assert len(key) == 32, "AES-256 key must be 32 bytes"
    assert len(iv) == 32, "IGE IV must be 32 bytes (two 16-byte halves)"
    assert len(data) % 16 == 0, "IGE input must be a multiple of 16 bytes"

    aes = AES.new(key, AES.MODE_ECB)
    prev_c, prev_p = iv[:16], iv[16:]
    out = bytearray()
    for offset in range(0, len(data), 16):
        block = data[offset:offset + 16]
        xored = bytes(a ^ b for a, b in zip(block, prev_c))
        cipher = aes.encrypt(xored)
        cipher = bytes(a ^ b for a, b in zip(cipher, prev_p))
        out += cipher
        prev_c, prev_p = cipher, block
    return bytes(out)


def ige_decrypt(key: bytes, iv: bytes, data: bytes) -> bytes:
    assert len(key) == 32 and len(iv) == 32 and len(data) % 16 == 0
    aes = AES.new(key, AES.MODE_ECB)
    prev_c, prev_p = iv[:16], iv[16:]
    out = bytearray()
    for offset in range(0, len(data), 16):
        block = data[offset:offset + 16]
        xored = bytes(a ^ b for a, b in zip(block, prev_p))
        plain = aes.decrypt(xored)
        plain = bytes(a ^ b for a, b in zip(plain, prev_c))
        out += plain
        prev_c, prev_p = block, plain
    return bytes(out)


def msg_key(auth_key: bytes, x: int, plaintext: bytes) -> bytes:
    """MTProto 2.0: SHA256(auth_key[88+x : 120+x] || plaintext)[8:24]."""
    digest = hashlib.sha256(auth_key[88 + x:120 + x] + plaintext).digest()
    return digest[8:24]


def key_iv(auth_key: bytes, x: int, mk: bytes) -> tuple[bytes, bytes]:
    a = hashlib.sha256(mk + auth_key[x:x + 36]).digest()
    b = hashlib.sha256(auth_key[40 + x:76 + x] + mk).digest()
    aes_key = a[0:8] + b[8:24] + a[24:32]
    aes_iv = b[0:8] + a[8:24] + b[24:32]
    return aes_key, aes_iv


def fmt(name: str, data: bytes) -> str:
    hexed = data.hex()
    chunks = [hexed[i:i + 64] for i in range(0, len(hexed), 64)]
    lines = "\n".join(f'    "{chunk}",' for chunk in chunks)
    return f"pub const {name}_HEX: &str = concat!(\n{lines}\n);"


def main() -> None:
    # --- AES-256-IGE KAT ---------------------------------------------------
    key = bytes(range(32))
    iv = bytes(range(0xA0, 0xC0))
    plaintext = bytes(range(64))

    ciphertext = ige_encrypt(key, iv, plaintext)
    assert ige_decrypt(key, iv, ciphertext) == plaintext

    print("// AES-256-IGE (generated by scripts/mtproto2-vectors/gen_vectors.py)")
    print(fmt("IGE_KAT_KEY", key))
    print(fmt("IGE_KAT_IV", iv))
    print(fmt("IGE_KAT_PLAINTEXT", plaintext))
    print(fmt("IGE_KAT_CIPHERTEXT", ciphertext))
    print()

    # --- MTProto 2.0 KDF KAT ----------------------------------------------
    auth_key = bytes((i * 7 + 11) % 256 for i in range(256))
    padded_plaintext = bytes(range(0x30, 0x30 + 48))

    for x, name in ((0, "CLIENT"), (8, "SERVER")):
        mk = msg_key(auth_key, x, padded_plaintext)
        aes_key, aes_iv = key_iv(auth_key, x, mk)
        print(f"// MTProto 2.0 KDF, x = {x} ({name} ->)")
        print(f'pub const MSG_KEY_{name}_HEX: &str = "{mk.hex()}";')
        print(f'pub const AES_KEY_{name}_HEX: &str = "{aes_key.hex()}";')
        print(f'pub const AES_IV_{name}_HEX: &str = "{aes_iv.hex()}";')
        print()


if __name__ == "__main__":
    main()